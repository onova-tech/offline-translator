// Spec 080: one on-demand language pack per language of packs/languages.tsv (generated by
// scripts/update-language-catalog.py), each built by the same packs/pack.gradle.kts.
file("packs/languages.tsv")
    .readLines()
    .filterNot { it.isBlank() || it.startsWith("#") || it.startsWith("code\t") }
    .map { it.substringBefore('\t') }
    .distinct()
    .forEach { code ->
        include(":packs:translate_$code")
        project(":packs:translate_$code").buildFileName = "../pack.gradle.kts"
    }

// Spec 082: the app's own speech, one on-demand pack per line of packs/speech.tsv (generated by
// scripts/update-speech-catalog.py): Whisper, espeak-ng's data and a voice per language, built by the same script.
file("packs/speech.tsv")
    .readLines()
    .filterNot { it.isBlank() || it.startsWith("#") || it.startsWith("pack\t") }
    .map { it.substringBefore('\t') }
    .forEach { pack ->
        include(":packs:$pack")
        project(":packs:$pack").buildFileName = "../pack.gradle.kts"
    }
