// Spec 080: one on-demand language pack per language of packs/languages.tsv (generated by
// scripts/update-language-catalog.py), each built by the same packs/pack.gradle.kts.
file("packs/languages.tsv")
    .readLines()
    .filterNot { it.isBlank() || it.startsWith("#") || it.startsWith("code\t") }
    .map { it.substringBefore('\t') }
    .distinct()
    .forEach { code ->
        include(":packs:translate_$code")
        project(":packs:translate_$code").buildFileName = "../pack.gradle.kts"
    }
